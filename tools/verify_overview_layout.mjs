import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { installMintFixture } from './fixtures/clear_mint.mjs';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '../benchmarks/refactor/frontend/node_modules/playwright/index.mjs');
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH || undefined, headless: true });
const output = 'output/verification/overview-layout';
await mkdir(output, { recursive: true });
const report = { checks: [], errors: [], screenshots: [] };
const context = await browser.newContext({ viewport: { width: 1536, height: 1024 }, locale: 'zh-CN', timezoneId: 'Asia/Shanghai', reducedMotion: 'reduce' });
await installMintFixture(context);
const page = await context.newPage();
page.setDefaultTimeout(8000);
await page.clock.setFixedTime(new Date('2026-10-22T04:00:00Z'));
page.on('pageerror', error => report.errors.push(String(error)));
const check = label => { report.checks.push(label); console.log(label); };
const screenshot = async name => { const path = `${output}/${name}.png`; await page.screenshot({ path }); report.screenshots.push(path); };
const layout = () => page.evaluate(() => Object.fromEntries(['.page-header', '.metrics', '.browser-pane', '.detail-panel'].map(selector => { const el = document.querySelector(selector); const box = el?.getBoundingClientRect(); return [selector, box ? { x: box.x, y: box.y, width: box.width, height: box.height } : null]; })));
const noOverflow = () => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight);
try {
  await page.goto('http://127.0.0.1:8765/?period=week&session=main&timezone=Asia%2FShanghai');
  await page.locator('.cost-bar').waitFor();
  await page.evaluate(() => document.fonts.ready);
  assert.equal(await page.locator('.metrics .metric-spark').count(), 2);
  assert.equal(await page.locator('.role-value[data-role="main"]').innerText(), '8');
  assert.equal(await page.locator('.role-value[data-role="agent"]').innerText(), '2');
  const initial = await layout();
  assert.equal(initial['.metrics'].height, 192);
  assert.equal(initial['.browser-pane'].height, initial['.detail-panel'].height);
  assert.ok(initial['.browser-pane'].y + initial['.browser-pane'].height <= 1024);
  await screenshot('projects');
  await page.getByRole('button', { name: '按会话', exact: true }).click();
  await page.locator('.sessions-table').waitFor();
  const rowHeight = await page.locator('.sessions-table tbody tr').first().evaluate(el => el.getBoundingClientRect().height);
  assert.ok(rowHeight <= 60, `Two-line conversation rows: ${rowHeight}`);
  await screenshot('overview');
  check('Overview metric cards and real-data mini-chart slots, equal fixed panel heights, denser conversation rows');

  await page.setViewportSize({ width: 1536, height: 800 });
  await page.locator('.browser-scroll').evaluate(el => el.scrollTop = 0);
  const beforeScroll = await layout();
  const list = await page.locator('.browser-scroll').boundingBox();
  await page.mouse.move(list.x + list.width / 2, list.y + list.height / 2);
  await page.mouse.wheel(0, 800);
  await page.waitForFunction(() => document.querySelector('.browser-scroll').scrollTop > 0);
  assert.deepEqual(await layout(), beforeScroll);
  assert.equal(await page.evaluate(() => scrollY), 0);
  await page.locator('.events-section > summary').click();
  const detail = await page.locator('.detail-scroll').boundingBox();
  await page.mouse.move(detail.x + detail.width / 2, detail.y + detail.height / 2);
  await page.mouse.wheel(0, 1000);
  await page.waitForFunction(() => document.querySelector('.detail-scroll').scrollTop > 0);
  assert.deepEqual(await layout(), beforeScroll);
  await page.evaluate(() => scrollTo(0, 700));
  assert.equal(await page.evaluate(() => scrollY), 0);
  check('Mouse-wheel list/detail scrolling and scroll chaining keep the header, metric cards and both panel boxes fixed');

  await page.locator('.preferences > summary').click();
  assert.equal(await page.locator('.preferences').evaluate(el => el.open), true);
  await page.locator('h1').click();
  assert.equal(await page.locator('.preferences').evaluate(el => el.open), false);
  await page.locator('.metric-breakdown > summary').click();
  await page.locator('h1').click();
  assert.equal(await page.locator('.metric-breakdown').evaluate(el => el.open), false);
  const globalPanel = page.getByRole('dialog', { name: '筛选', exact: true });
  await page.getByRole('button', { name: '筛选', exact: true }).click();
  await globalPanel.waitFor();
  await globalPanel.getByRole('group', { name: '状态', exact: true }).getByRole('button', { name: '已归档', exact: true }).click();
  assert.equal(await globalPanel.isVisible(), true);
  await globalPanel.getByRole('button', { name: '清除筛选', exact: true }).click();
  assert.equal(new URL(page.url()).searchParams.has('source'), false, 'Clear filters must work on the first click');
  await page.keyboard.press('Escape');
  assert.equal(await globalPanel.isVisible(), false);
  await page.getByRole('button', { name: '筛选', exact: true }).click();
  await page.locator('h1').click();
  assert.equal(await globalPanel.isVisible(), false);
  await page.locator('.sessions-table .session-title').first().click();
  check('Preferences, token breakdown and filters dismiss on outside interaction without closing during inner interaction');

  await page.setViewportSize({ width: 1536, height: 1024 });
  const beforeCalendar = await layout();
  const beforeUrl = page.url();
  await page.locator('.calendar-trigger').click();
  const calendar = page.locator('.calendar-panel');
  await calendar.waitFor();
  assert.equal(await calendar.evaluate(el => el.matches(':modal')), true);
  assert.equal(await calendar.getAttribute('aria-modal'), 'true');
  const maskColor = await calendar.evaluate(el => getComputedStyle(el, '::backdrop').backgroundColor);
  assert.notEqual(maskColor, 'rgba(0, 0, 0, 0)');
  await calendar.locator('.calendar-heading').click();
  assert.equal(await calendar.count(), 1);
  await calendar.locator('[data-date="2026-10-19"]').click();
  await calendar.locator('[data-date="2026-10-22"]').click();
  assert.equal(page.url(), beforeUrl);
  assert.deepEqual(await layout(), beforeCalendar);
  await screenshot('calendar-mask');
  await page.mouse.click(10, 10);
  await calendar.waitFor({ state: 'detached' });
  assert.equal(page.url(), beforeUrl);
  assert.deepEqual(await layout(), beforeCalendar);
  assert.equal(await page.locator('.calendar-trigger').evaluate(el => el === document.activeElement), true);
  await page.locator('.calendar-trigger').click();
  assert.equal(await page.getByLabel('结束日期', { exact: true }).inputValue(), '2026/10/25');
  await page.keyboard.press('Escape');
  await calendar.waitFor({ state: 'detached' });
  assert.equal(await page.locator('.detail-panel').count(), 1);
  check('Date picker has a global native mask, keeps inner clicks open, discards drafts on outside click/Escape and restores focus');

  await page.locator('.main-nav').getByRole('button', { name: '设备数据', exact: true }).click();
  const manager = page.locator('dialog:not(.calendar-panel)');
  await manager.waitFor();
  await manager.locator('header').click();
  assert.equal(await manager.count(), 1);
  await page.mouse.click(10, 10);
  await manager.waitFor({ state: 'detached' });
  await page.locator('.main-nav').getByRole('button', { name: '设备数据', exact: true }).click();
  await page.keyboard.press('Escape');
  await manager.waitFor({ state: 'detached' });
  check('Device-data modal dismisses on backdrop and Escape; clicking its contents keeps it open');

  await page.locator('.detail-panel').getByRole('button', { name: '关闭', exact: true }).click();
  for (const [width, height] of [[1920,1080], [1366,768], [1101,700], [800,600], [390,844], [320,640]]) {
    await page.setViewportSize({ width, height });
    await page.evaluate(() => new Promise(requestAnimationFrame));
    assert.equal(await noOverflow(), true, `Viewport shell fits ${width}x${height}`);
    const panels = await layout();
    assert.ok(panels['.browser-pane'].height > 80, 'List remains usable in short viewports');
    assert.ok(panels['.browser-pane'].y + panels['.browser-pane'].height <= height);
    await page.locator('.calendar-trigger').click();
    await calendar.waitFor();
    const box = await calendar.boundingBox();
    const apply = await calendar.getByRole('button', { name: '应用日期', exact: true }).boundingBox();
    assert.ok(box.x >= 0 && box.y >= 0 && box.x + box.width <= width && box.y + box.height <= height);
    assert.ok(apply.y >= box.y && apply.y + apply.height <= height);
    if (width === 390) await screenshot('mobile-calendar-mask');
    await page.mouse.click(2, 2);
    await calendar.waitFor({ state: 'detached' });
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.browser-scroll').evaluate(el => el.scrollTop = 0);
  await page.locator('.sessions-table .session-title').first().click();
  await page.locator('.detail-panel[aria-modal="true"]').waitFor();
  await screenshot('mobile-detail');
  await page.mouse.click(2, 400);
  await page.locator('.detail-panel').waitFor({ state: 'detached' });
  await screenshot('mobile-list');
  check('1920/1366/1101/800/390/320px fixed layouts, small-height calendars, visible Apply controls and mobile detail backdrop dismissal');
  assert.deepEqual(report.errors, []);
  report.rowHeight = rowHeight;
  report.passed = true;
} catch (error) {
  report.failure = String(error);
  await page.screenshot({ path: `${output}/failure.png` });
  throw error;
} finally {
  await writeFile(`${output}/checks.json`, JSON.stringify(report, null, 2));
  await browser.close();
}
