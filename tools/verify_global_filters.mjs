import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { installMintFixture } from './fixtures/clear_mint.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '../benchmarks/refactor/frontend/node_modules/playwright/index.mjs');
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH || undefined, headless: true });
const output = 'output/verification/global-filters';
await mkdir(output, { recursive: true });
const context = await browser.newContext({ viewport: { width: 1536, height: 1024 }, locale: 'zh-CN', reducedMotion: 'reduce' });
await installMintFixture(context);
const page = await context.newPage();
page.setDefaultTimeout(8000);
const errors = [], checks = [];
page.on('pageerror', error => errors.push(String(error)));
const panel = page.getByRole('dialog', { name: '筛选', exact: true });
const toggle = page.locator('.filter-toggle');
const choose = async (group, option) => {
  await panel.getByRole('group', { name: group, exact: true }).getByRole('button', { name: option, exact: true }).click();
  await panel.getByRole('button', { name: '确定', exact: true }).click();
  await toggle.click();
};
const check = message => { checks.push(message); console.log(message); };
const tokenValue = () => page.locator('.metrics article').first().locator('strong').first().innerText();
const metricsTop = () => page.locator('.metrics').evaluate(el => el.getBoundingClientRect().top);
const clear = () => page.locator('.global-filters .clear-filters').click();
const bounds = async locator => {
  const box = await locator.boundingBox();
  const { width, height } = page.viewportSize();
  assert.ok(box && box.x >= 0 && box.y >= 0 && box.x + box.width <= width && box.y + box.height <= height, JSON.stringify(box));
};
try {
  await page.goto('http://127.0.0.1:8765/?period=week&timezone=Asia%2FShanghai');
  await page.locator('.task-row').first().waitFor();
  await page.evaluate(() => document.fonts.ready);
  assert.ok((await page.locator('.global-filters').boundingBox()).y < await metricsTop());
  assert.equal(await page.locator('.browser-pane input[type="search"]').count(), 0);
  assert.equal(await page.locator('.list-actions .sorting').count(), 1);
  assert.equal(await page.locator('.global-toolbar .date-controls').count(), 1);
  assert.equal(await page.locator('.page-header .date-controls').count(), 1);
  assert.equal(await page.getByText('作用于下方统计与列表', { exact: true }).count(), 0);
  const searchBox = await page.locator('.global-search').boundingBox();
  const dateBox = await page.locator('.date-controls').boundingBox();
  const filterBox = await toggle.boundingBox();
  const titleBox = await page.locator('.brand-title').boundingBox();
  assert.ok(searchBox.x >= titleBox.x + titleBox.width + 20);
  assert.ok(Math.abs(searchBox.y + searchBox.height / 2 - titleBox.y - titleBox.height / 2) < 2);
  assert.ok(searchBox.width <= 320);
  assert.ok(Math.abs(searchBox.y - dateBox.y) < 4 && Math.abs(filterBox.y - dateBox.y) < 4);
  await page.screenshot({ path: `${output}/desktop-compact.png` });
  const top = await metricsTop();
  await toggle.click();
  await panel.waitFor();
  await bounds(panel);
  assert.equal(await metricsTop(), top);
  assert.equal(await panel.getByRole('group').count(), 4);
  assert.equal(await panel.locator('details').count(), 0);
  assert.equal(await panel.locator('.filter-header').count(), 0);
  assert.equal(await panel.getByText('选择后即时生效', { exact: true }).count(), 0);
  await choose('状态', '已归档');
  assert.equal(new URL(page.url()).searchParams.get('source'), 'archived');
  assert.equal(await panel.isVisible(), true);
  await page.waitForFunction(() => document.querySelector('.list-count').textContent.includes('1'));
  assert.match(await page.locator('.active-filters').innerText(), /状态: 已归档/);
  await choose('代理', '仅子代理');
  await choose('环境', 'Local');
  await choose('模型', 'GPT-6.1 Sol');
  assert.equal(await toggle.getAttribute('aria-label'), '筛选 · 4');
  assert.match(await page.locator('.active-filters').innerText(), /代理: 仅子代理/);
  assert.equal((await page.locator('.brand-title').boundingBox()).y, titleBox.y);
  await page.keyboard.press('Escape');
  assert.equal(await panel.isVisible(), false);
  assert.equal(await toggle.evaluate(el => el === document.activeElement), true);
  await page.screenshot({ path: `${output}/desktop-selected.png` });
  await clear();
  assert.equal(await page.locator('.active-filters').count(), 0);
  for (const key of ['source', 'agents', 'model', 'environment']) assert.equal(new URL(page.url()).searchParams.has(key), false);
  assert.equal(new URL(page.url()).searchParams.get('period'), 'week');
  check('Global controls precede metrics; list sorting stays local; four direct filters apply on confirmation and Escape restores focus without layout shift');

  await page.waitForFunction(() => document.querySelector('.list-count').textContent.includes('3'));
  const beforeTokens = await tokenValue();
  await page.getByRole('searchbox').fill('指南');
  await page.waitForFunction(() => document.querySelector('.list-count').textContent.includes('1'));
  assert.notEqual(await tokenValue(), beforeTokens);
  assert.equal(await toggle.getAttribute('aria-label'), '筛选');
  await toggle.click();
  await choose('状态', '已归档');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '移除筛选: 状态: 已归档', exact: true }).click();
  assert.equal(new URL(page.url()).searchParams.get('search'), '指南');
  assert.equal(new URL(page.url()).searchParams.has('source'), false);
  await page.getByRole('button', { name: '清除搜索', exact: true }).click();
  await page.getByRole('searchbox').fill('definitely-no-match');
  await page.locator('.empty').waitFor();
  await page.locator('.empty').getByRole('button', { name: '清除筛选', exact: true }).click();
  await page.locator('.task-row').first().waitFor();
  await toggle.focus();
  await page.keyboard.press('Enter');
  await panel.waitFor();
  await choose('状态', '活跃');
  await panel.getByRole('button', { name: '清除筛选', exact: true }).click();
  await panel.getByRole('button', { name: '确定', exact: true }).click();
  await toggle.click();
  assert.equal(new URL(page.url()).searchParams.has('source'), false);
  assert.equal(await panel.isVisible(), true);
  await page.locator('h1').click();
  assert.equal(await panel.isVisible(), false);
  await page.goBack();
  assert.equal(new URL(page.url()).searchParams.get('source'), 'active');
  assert.match(await page.locator('.active-filters').innerText(), /状态: 活跃/);
  await clear();
  check('Search updates cards and list, filter count excludes search, chips remove one condition, clear preserves date range, empty-state reset and browser history work');

  for (const width of [1366, 1200, 1024, 1000, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await bounds(toggle);
    await bounds(page.locator('.date-controls'));
    const controls = await page.locator('.global-filters').boundingBox();
    assert.ok(controls.y + controls.height <= await metricsTop());
    await bounds(page.locator('.list-actions .sorting'));
    await toggle.click();
    await panel.waitFor();
    await bounds(panel);
    await choose('状态', '已归档');
    await bounds(panel);
    await page.screenshot({ path: `${output}/filters-${width}.png` });
    await panel.getByRole('button', { name: '关闭', exact: true }).click();
    await clear();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.getByRole('button', { name: '按会话', exact: true }).click();
    await page.locator('.sessions-table .session-title').first().waitFor();
    await bounds(page.locator('.list-actions .sorting'));
    await page.getByRole('button', { name: '按项目', exact: true }).click();
  }
  check('Search, filters and dates share a compact global area above metrics at 1366/1200/1024/1000/768/390/320px in both list modes');
  await page.setViewportSize({ width: 1536, height: 1024 });
  await page.locator('.task-row:not(.group-row)').first().click();
  await page.locator('.detail-panel').waitFor();
  await toggle.click();
  await panel.waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await panel.isVisible(), false);
  assert.equal(await page.locator('.detail-panel').isVisible(), true);
  check('Escape closes global filters before the open conversation detail panel');
  const english = await browser.newContext({ viewport: { width: 320, height: 844 }, reducedMotion: 'reduce' });
  await installMintFixture(english, { language: 'en' });
  const enPage = await english.newPage();
  await enPage.goto('http://127.0.0.1:8765/?period=week');
  await enPage.locator('.task-row').first().waitFor();
  await enPage.locator('.filter-toggle').click();
  await enPage.getByRole('dialog', { name: 'Filters' }).waitFor();
  assert.equal(await enPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await enPage.screenshot({ path: `${output}/english-320.png` });
  await english.close();
  check('English filters remain usable at 320px');
  assert.deepEqual(errors, []);
  await writeFile(`${output}/checks.json`, JSON.stringify({ passed: true, checks, errors }, null, 2));
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` });
  throw error;
} finally { await browser.close(); }
